"""Run every query in sql/analysis_queries.sql and write results to reports/sql_results/*.csv
plus a combined markdown file (reports/sql_results.md).

Usage:  python src/run_sql.py
"""
import re
import sqlite3
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SQL = (ROOT / "sql" / "analysis_queries.sql").read_text()
OUT = ROOT / "reports" / "sql_results"
OUT.mkdir(parents=True, exist_ok=True)


def parse(text: str):
    blocks = re.split(r"^-- name: ", text, flags=re.M)[1:]
    for b in blocks:
        name, rest = b.split("\n", 1)
        q = re.search(r"^-- question: (.*)$", rest, flags=re.M).group(1)
        body = "\n".join(l for l in rest.splitlines() if not l.startswith("-- question:")).strip()
        yield name.strip(), q.strip(), body


def main() -> None:
    con = sqlite3.connect(ROOT / "data" / "olist.db")
    md = ["# SQL query results\n", "Auto-generated by `src/run_sql.py`. Each section = one query in `sql/analysis_queries.sql`.\n"]
    for name, question, body in parse(SQL):
        df = pd.read_sql_query(body, con)
        df.to_csv(OUT / f"{name}.csv", index=False)
        md += [f"## {name}", f"**Question:** {question}\n", df.head(20).to_markdown(index=False), ""]
        print(f"{name:40s} {len(df):>4d} rows")
    (ROOT / "reports" / "sql_results.md").write_text("\n".join(md))


if __name__ == "__main__":
    main()
